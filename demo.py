"""
demo.py — DermaAgent Interactive Demo (CLI + Gradio Web UI)
==============================================================

Provides two execution modes for demonstrating the DermaAgent system:

    a) **CLI Mode** (``--cli``):
       End-to-end sample test with terminal logging showing the
       Agent's Thought/Action/Observation reasoning loop.

    b) **Gradio Web UI** (default):
       Lightweight single-page interface where users upload a skin image,
       ask questions, and see side-by-side original image + Grad-CAM
       heatmap + agent reasoning log + final diagnostic report.

Usage
-----
    # Gradio Web UI (default)
    python demo.py

    # CLI mode with a specific image
    python demo.py --cli --image path/to/lesion.jpg

    # CLI mode with custom query
    python demo.py --cli --image lesion.jpg --query "Is this melanoma?"

    # Specify LLM provider
    python demo.py --provider openai --model gpt-4o

Author  : DermaAgent Assessment Module
License : MIT
"""

