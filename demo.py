def main():
    """Parse arguments and launch the appropriate demo mode."""
    parser = argparse.ArgumentParser(
        description="DermaAgent — AI Skin Lesion Diagnostic Demo",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python demo.py                          # Launch Gradio Web UI
  python demo.py --cli --image lesion.jpg  # CLI mode
  python demo.py --provider openai         # Use OpenAI backend
  python demo.py --port 7861               # Custom port for Web UI
        """,
    )

    parser.add_argument(
        "--cli",
        action="store_true",
        help="Run in CLI mode instead of Gradio Web UI.",
    )
    parser.add_argument(
        "--image",
        type=str,
        default=None,
        help="Path to skin lesion image (required for CLI mode).",
    )
    parser.add_argument(
        "--query",
        type=str,
        default="Analyze this skin lesion and provide a comprehensive diagnostic assessment.",
        help="Patient query for analysis.",
    )
    parser.add_argument(
        "--provider",
        type=str,
        default=None,
        choices=["openai", "qwen", "groq", "huggingface", "ollama"],
        help="LLM provider to use.",
    )
    parser.add_argument(
        "--model",
        type=str,
        default=None,
        help="Specific LLM model name.",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=7860,
        help="Port for Gradio Web UI (default: 7860).",
    )
    parser.add_argument(
        "--share",
        action="store_true",
        help="Create a public Gradio share link.",
    )

    args = parser.parse_args()

    if args.cli:
        # ---- CLI Mode ----
        if not args.image:
            # Try to find a sample image
            sample_dir = os.path.join(_AGENT_ROOT, "samples")
            if os.path.isdir(sample_dir):
                samples = glob.glob(os.path.join(sample_dir, "*.jpg")) + \
                          glob.glob(os.path.join(sample_dir, "*.png"))
                if samples:
                    args.image = samples[0]
                    print(f"  ℹ️  No --image specified. Using sample: {args.image}")

            if not args.image:
                print("  ❌ CLI mode requires --image argument.")
                print("     Usage: python demo.py --cli --image path/to/lesion.jpg")
                sys.exit(1)

        run_cli_demo(
            image_path=args.image,
            query=args.query,
            provider=args.provider,
            model_name=args.model,
        )
    else:
        # ---- Gradio Web UI Mode ----
        print("\n" + "═" * 60)
        print("  🌐 DermaAgent — Gradio Web UI")
        print("═" * 60)
        print(f"  Starting on port {args.port}...")
        print(f"  Open: http://localhost:{args.port}")
        if args.share:
            print("  Public share link will be generated.")
        print("═" * 60 + "\n")

        demo = create_gradio_ui(
            provider=args.provider,
            model_name=args.model,
        )
        demo.launch(
            server_port=args.port,
            share=args.share,
            show_error=True,
        )


if __name__ == "__main__":
    main()
