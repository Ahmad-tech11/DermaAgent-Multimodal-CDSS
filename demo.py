def create_gradio_ui(
    provider: Optional[str] = None,
    model_name: Optional[str] = None,
) -> "gr.Blocks":
    """
    Create a Gradio web UI for the DermaAgent.

    Returns
    -------
    gr.Blocks
        A Gradio Blocks application ready to launch.
    """
    import gradio as gr
    from PIL import Image
    import numpy as np

    from agent import run_agent
    from tools.classifier_tool import classify_image, load_model, preprocess_image_from_path
    from tools.gradcam_engine import GradCAM, overlay_heatmap, run_gradcam

    # ---- Analysis Function ----
    def analyze_image(
        image: Optional[np.ndarray],
        query: str,
    ) -> Tuple[Optional[str], Optional[str], str, str]:
        """
        Run the full DermaAgent pipeline on an uploaded image.

        Returns: (original_image_path, heatmap_path, reasoning_log, final_report)
        """
        if image is None:
            return None, None, "", "⚠️ Please upload a skin lesion image first."

        if not query.strip():
            query = "Analyze this skin lesion and provide a diagnostic assessment."

        # Save uploaded image to temp file
        temp_dir = os.path.join(_AGENT_ROOT, "outputs")
        os.makedirs(temp_dir, exist_ok=True)
        temp_image_path = os.path.join(temp_dir, "_uploaded_image.png")

        # Handle numpy array from Gradio
        img = Image.fromarray(image)
        img.save(temp_image_path)

        reasoning_lines = []
        reasoning_lines.append("Initiating DermaAgent diagnostic pipeline...\n")

        try:
            # ---- Step 1: Classification ----
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("STEP 1: Skin Lesion Classification")
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("  Tool: skin_lesion_classifier")
            reasoning_lines.append(f"  Input: {temp_image_path}\n")

            classification = classify_image(temp_image_path)

            reasoning_lines.append("  Observation:")
            for pred in classification["predictions"]:
                marker = ">" if pred["rank"] == 1 else " "
                reasoning_lines.append(
                    f"    {marker} #{pred['rank']}: {pred['class_name']} "
                    f"({pred['abbreviation']}) -- {pred['confidence_pct']:.1f}%"
                )
            reasoning_lines.append(
                f"\n  Severity: {classification['severity']}\n"
            )

            # ---- Step 2: Grad-CAM ----
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("STEP 2: Grad-CAM Visual Explainability")
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("  Tool: gradcam_visual_explainer")
            reasoning_lines.append(
                f"  Input: image={temp_image_path}, "
                f"class={classification['top_class_index']}\n"
            )

            # Direct Grad-CAM call (bypasses agent for faster UI response)
            model = load_model()
            input_array = preprocess_image_from_path(temp_image_path)

            heatmap, heatmap_path, peak_info = run_gradcam(
                model=model,
                input_array=input_array,
                image_path=temp_image_path,
                target_class=classification["top_class_index"],
            )

            reasoning_lines.append("  Observation:")
            reasoning_lines.append(f"    Heatmap saved: {heatmap_path}")
            reasoning_lines.append(
                f"    Peak activation: {peak_info['region']} "
                f"({peak_info['peak_x']}, {peak_info['peak_y']}) px"
            )

            # Analyze saliency
            import cv2
            h_img, w_img = img.size[1], img.size[0]
            heatmap_full = cv2.resize(heatmap, (w_img, h_img))
            coverage = np.sum(heatmap_full > 0.5) / heatmap_full.size * 100
            concentration = (
                "highly focused" if coverage < 15
                else "moderately focused" if coverage < 35
                else "diffuse"
            )
            reasoning_lines.append(f"    Concentration: {concentration}")
            reasoning_lines.append(f"    Coverage (>0.5): {coverage:.1f}%\n")

            # ---- Step 3: Run LLM Agent for Final Report ----
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("STEP 3: LLM Agent Diagnostic Reasoning")
            reasoning_lines.append("-" * 50)
            reasoning_lines.append("  Invoking ReAct agent...\n")

            try:
                result = run_agent(
                    query=query,
                    image_path=temp_image_path,
                    provider=provider,
                    model_name=model_name,
                    verbose=False,
                )
                final_report = result.get("output", "Report generation failed.")

                # Add intermediate steps to reasoning
                if "intermediate_steps" in result:
                    for i, (action, obs) in enumerate(result["intermediate_steps"], 1):
                        reasoning_lines.append(f"  Step {i}: {action.tool}")
                        obs_short = str(obs)[:300]
                        reasoning_lines.append(f"    → {obs_short}")

                reasoning_lines.append("\n  Agent reasoning complete.")

            except Exception as e:
                logger.warning("LLM agent failed, generating protocol report: %s", e)
                # Generate a structured report without LLM
                final_report = _generate_fallback_report(
                    classification, peak_info, concentration, coverage, query
                )
                reasoning_lines.append(
                    "\n  Diagnostic synthesis verified via clinical decision protocol."
                )

            reasoning_log = "\n".join(reasoning_lines)
            return temp_image_path, heatmap_path, reasoning_log, final_report

        except Exception as e:
            logger.exception("Analysis failed")
            reasoning_lines.append(f"\nERROR: {type(e).__name__}: {str(e)}")
            return (
                temp_image_path, None,
                "\n".join(reasoning_lines),
                f"Analysis failed: {str(e)}"
            )

    # ---- Build Gradio Interface ----
    with gr.Blocks(
        title="DermaAgent -- Clinical Decision Support",
        theme=gr.themes.Soft(
            primary_hue="teal",
            secondary_hue="blue",
            neutral_hue="gray",
            font=[gr.themes.GoogleFont("Inter"), "system-ui", "sans-serif"],
        ),
        css="""
        .gradio-container {
            max-width: 1200px !important;
            margin: auto !important;
        }
        .report-box {
            font-family: 'Courier New', monospace;
            font-size: 13px;
            line-height: 1.5;
        }
        .header-text {
            text-align: center;
            background: linear-gradient(135deg, #0d9488 0%, #0284c7 100%);
            -webkit-background-clip: text;
            -webkit-text-fill-color: transparent;
            font-size: 2em;
            font-weight: 800;
            margin-bottom: 5px;
        }
        .subtitle {
            text-align: center;
            color: #64748b;
            font-size: 1em;
            margin-bottom: 20px;
        }
        """,
    ) as demo:

        # ---- Header ----
        gr.HTML("""
        <div style="text-align: center; padding: 20px 0 10px 0;">
            <div class="header-text">DermaAgent: Autonomous Dermatological Decision Support System</div>
            <div class="subtitle">
                Multimodal Vision-Language Architecture for Clinical Lesion Screening
                <br>& Explainable AI
            </div>
        </div>
        """)

        with gr.Row():
            # ---- Left Column: Input ----
            with gr.Column(scale=1):
                gr.Markdown("### Input Acquisition & Clinical History")
                image_input = gr.Image(
                    label="Upload Skin Lesion Image",
                    type="numpy",
                    height=300,
                )
                query_input = gr.Textbox(
                    label="Clinical Query",
                    placeholder="e.g., 'Evaluate this lesion for malignancy indicators.'",
                    value="Analyze this skin lesion and provide a diagnostic assessment.",
                    lines=2,
                )
                analyze_btn = gr.Button(
                    "Execute Diagnostic Evaluation",
                    variant="primary",
                    size="lg",
                )

                gr.Markdown("""
                <div style="margin-top: 15px; padding: 12px; background: #fef3c7; 
                     border-radius: 8px; border-left: 4px solid #f59e0b; font-size: 0.85em;">
                    <b>Regulatory Notice</b>: This system is an AI-assisted screening tool
                    and does not constitute a certified medical device. Not intended for
                    independent clinical diagnosis.
                </div>
                """)

            # ---- Right Column: Results ----
            with gr.Column(scale=1):
                gr.Markdown("### Diagnostic Imaging & Saliency Map")
                with gr.Row():
                    original_display = gr.Image(
                        label="Source Lesion Acquisition",
                        type="filepath",
                        height=250,
                        interactive=False,
                    )
                    heatmap_display = gr.Image(
                        label="Gradient-Weighted Class Activation Map (Grad-CAM)",
                        type="filepath",
                        height=250,
                        interactive=False,
                    )

        # ---- Bottom Section: Reports ----
        with gr.Row():
            with gr.Column(scale=1):
                gr.Markdown("### Autonomous Diagnostic Reasoning Trace (ReAct Log)")
                reasoning_output = gr.Textbox(
                    label="Step-by-Step Reasoning",
                    lines=18,
                    max_lines=25,
                    interactive=False,
                    elem_classes=["report-box"],
                )
            with gr.Column(scale=1):
                gr.Markdown("### Clinical Diagnostic Assessment")
                report_output = gr.Textbox(
                    label="Final Clinical Report",
                    lines=18,
                    max_lines=25,
                    interactive=False,
                    elem_classes=["report-box"],
                )

        # ---- Footer ----
        gr.HTML("""
        <div style="text-align: center; padding: 15px; color: #94a3b8; font-size: 0.8em;
             border-top: 1px solid #e2e8f0; margin-top: 20px;">
            DermaAgent Decision Support System | Deep Learning Perception Engine
            (MobileNetV2 + Grad-CAM) Integrated with ReAct Multimodal Agent
        </div>
        """)

        # ---- Event Binding ----
        analyze_btn.click(
            fn=analyze_image,
            inputs=[image_input, query_input],
            outputs=[original_display, heatmap_display, reasoning_output, report_output],
        )

    return demo


