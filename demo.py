def run_cli_demo(
    image_path: str,
    query: str = "Analyze this skin lesion and provide a diagnostic assessment.",
    provider: Optional[str] = None,
    model_name: Optional[str] = None,
) -> None:
    """
    Run the DermaAgent in CLI mode with detailed terminal output.

    Parameters
    ----------
    image_path : str
        Path to the skin lesion image to analyze.
    query : str
        Patient query / analysis request.
    provider : str, optional
        LLM provider override.
    model_name : str, optional
        LLM model override.
    """
    from agent import run_agent

    # ---- Banner ----
    print("\n" + "═" * 70)
    print("  🔬 DermaAgent — CLI Diagnostic Demo")
    print("═" * 70)
    print(f"  Image : {image_path}")
    print(f"  Query : {query}")
    print("═" * 70 + "\n")

    # Validate image
    if not os.path.isfile(image_path):
        print(f"  ❌ ERROR: Image file not found: {image_path}")
        print("     Please provide a valid image path with --image flag.")
        sys.exit(1)

    # ---- Run Agent ----
    print("  ⏳ Starting DermaAgent analysis...\n")
    print("─" * 70)
    print("  AGENT REASONING TRACE (Thought / Action / Observation)")
    print("─" * 70 + "\n")

    start_time = time.time()

    try:
        result = run_agent(
            query=query,
            image_path=image_path,
            provider=provider,
            model_name=model_name,
            verbose=True,  # Show full reasoning trace
        )
    except Exception as e:
        logger.warning("LLM agent unavailable (%s: %s). Generating rule-based report fallback...", type(e).__name__, e)
        from tools.classifier_tool import classify_image, load_model, preprocess_image_from_path
        from tools.gradcam_engine import run_gradcam
        import cv2
        import numpy as np

        classification = classify_image(image_path)
        model = load_model()
        input_array = preprocess_image_from_path(image_path)
        heatmap, heatmap_path, peak_info = run_gradcam(
            model=model,
            input_array=input_array,
            image_path=image_path,
            target_class=classification["top_class_index"],
        )
        img_bgr = cv2.imread(image_path)
        h_img, w_img = img_bgr.shape[:2]
        heatmap_full = cv2.resize(heatmap, (w_img, h_img))
        coverage = float(np.sum(heatmap_full > 0.5) / heatmap_full.size * 100)
        concentration = (
            "highly focused" if coverage < 15
            else "moderately focused" if coverage < 35
            else "diffuse"
        )
        report_text = _generate_fallback_report(
            classification, peak_info, concentration, coverage, query
        )
        result = {"output": report_text, "intermediate_steps": []}

    elapsed = time.time() - start_time

    # ---- Display Results ----
    print("\n" + "─" * 70)
    print("  INTERMEDIATE STEPS")
    print("─" * 70)

    if "intermediate_steps" in result:
        for i, (action, observation) in enumerate(result["intermediate_steps"], 1):
            print(f"\n  Step {i}:")
            print(f"    Tool: {action.tool}")
            print(f"    Input: {action.tool_input}")
            # Truncate long observations for display
            obs_display = str(observation)
            if len(obs_display) > 500:
                obs_display = obs_display[:500] + "... [truncated]"
            print(f"    Observation: {obs_display}")

    print("\n" + "═" * 70)
    print("  FINAL DIAGNOSTIC REPORT")
    print("═" * 70)
    print(result.get("output", "No output generated."))
    print("═" * 70)
    print(f"\n  ⏱  Total analysis time: {elapsed:.1f} seconds")

    # Check for generated heatmaps
    output_dir = os.path.join(_AGENT_ROOT, "outputs")
    heatmaps = sorted(glob.glob(os.path.join(output_dir, "cam_*.png")))
    if heatmaps:
        print(f"  🗺️  Grad-CAM heatmap: {heatmaps[-1]}")

    print("\n  ✅ CLI demo complete.\n")


